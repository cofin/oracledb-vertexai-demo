"""Re-entrant agent execution loop with dynamic tool dispatching."""

from collections.abc import AsyncIterator

from app.domain.ai.runtime._context import CallContext
from app.domain.ai.runtime._model import GeminiModelClient
from app.domain.ai.runtime._spec import AgentSpec, SpecTree, fence_context_block
from app.domain.ai.runtime._tools import Tool, ToolDeclaration, execute_parallel
from app.domain.ai.runtime._types import AgentEvent, AgentLimits, Content, FunctionCall, FunctionResponse, Part

__all__ = ("AgentRuntime",)


class AgentRuntime:
    """Core re-entrant agent execution loop."""

    def __init__(self, model_client: GeminiModelClient, limits: AgentLimits | None = None) -> None:
        """Initialize the agent runtime with model client and execution limits.

        Args:
            model_client: Client managing model communication.
            limits: Execution safety limits for turns and tool calls.
        """
        self._model_client = model_client
        self._limits = limits or AgentLimits()

    async def execute_turn(
        self,
        *,
        spec_tree: SpecTree,
        session_id: str,
        invocation_id: str,
        user_message: str,
        ctx: CallContext,
        history: list[AgentEvent] | None = None,
        dynamic_context: str | None = None,
    ) -> AsyncIterator[AgentEvent]:
        """Execute one re-entrant conversation turn until completion or budget exhaustion.

        Args:
            spec_tree: Agent hierarchy specification tree.
            session_id: Session identifier.
            invocation_id: Turn invocation identifier.
            user_message: Incoming user prompt message.
            ctx: Active CallContext for tool execution.
            history: Optional conversation history events.
            dynamic_context: Optional dynamic runtime context string.

        Yields:
            AgentEvent instances generated by model streaming or tool execution.
        """
        current_spec = spec_tree.root
        history_events = list(history or [])
        contents: list[Content] = [ev.content for ev in history_events if ev.content]

        user_text = user_message
        if dynamic_context:
            fenced = fence_context_block("ACTIVE_SESSION_CONTEXT", dynamic_context)
            user_text = f"{user_message}\n\n{fenced}"

        contents.append(Content(role="user", parts=[Part(text=user_text)]))

        model_calls = 0
        tool_calls_count = 0

        while model_calls < self._limits.max_model_calls_per_turn:
            model_calls += 1
            tools_map: dict[str, Tool] = {t.name: t for t in current_spec.tools}
            tool_decls: list[ToolDeclaration] = [t.declaration() for t in current_spec.tools]

            pending_calls: list[FunctionCall] = []

            async for event in self._model_client.generate_stream(
                contents, tools=tool_decls, system_instruction=current_spec.static_instruction, model=current_spec.model
            ):
                event.session_id = session_id
                event.invocation_id = invocation_id
                event.turn = ctx.turn
                event.agent = current_spec.name
                yield event

                if event.content and event.content.parts:
                    pending_calls.extend(p.function_call for p in event.content.parts if p.function_call)

            if not pending_calls:
                break

            tool_calls_count += len(pending_calls)
            if tool_calls_count > self._limits.max_tool_calls_per_turn:
                yield AgentEvent(
                    session_id=session_id,
                    invocation_id=invocation_id,
                    agent=current_spec.name,
                    finish_reason="TOOL_LIMIT_EXCEEDED",
                    content=Content(role="model", parts=[Part(text="Tool execution limit reached for this turn.")]),
                )
                break

            current_spec, response_parts = await self._dispatch_tools(
                pending_calls=pending_calls,
                current_spec=current_spec,
                spec_tree=spec_tree,
                tools_map=tools_map,
                ctx=ctx,
                contents=contents,
            )

            yield AgentEvent(
                session_id=session_id,
                invocation_id=invocation_id,
                agent=current_spec.name,
                content=Content(role="user", parts=response_parts),
            )

    async def _dispatch_tools(
        self,
        *,
        pending_calls: list[FunctionCall],
        current_spec: AgentSpec,
        spec_tree: SpecTree,
        tools_map: dict[str, Tool],
        ctx: CallContext,
        contents: list[Content],
    ) -> tuple[AgentSpec, list[Part]]:
        """Dispatch parallel tools, update delegation target, and record conversation content."""
        responses: list[FunctionResponse] = await execute_parallel(pending_calls, tools_map, ctx)

        next_spec = current_spec
        for resp in responses:
            if resp.name == "transfer_to_agent":
                target_name = str(resp.response.get("transferred_to", ""))
                if target_name:
                    next_spec = spec_tree.resolve(target_name)

        response_parts = [Part(function_response=r) for r in responses]
        contents.extend([
            Content(role="model", parts=[Part(function_call=c) for c in pending_calls]),
            Content(role="user", parts=response_parts),
        ])
        return next_spec, response_parts
