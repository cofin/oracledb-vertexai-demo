"""Re-entrant agent execution loop with TurnBudget and SpanManager instrumentation."""

from __future__ import annotations

from typing import TYPE_CHECKING, Any

import msgspec
from litestar_mcp.agent import BudgetExceededError, TurnBudget
from litestar_mcp.core.observability import SpanManager

from app.domain.ai.runtime._spec import AgentSpec, SpecTree, fence_context_block
from app.domain.ai.runtime._tools import Tool, ToolDeclaration, execute_parallel
from app.domain.ai.runtime._types import AgentEvent, AgentLimits, Content, FunctionCall, FunctionResponse, Part

if TYPE_CHECKING:
    from collections.abc import AsyncIterator

    from app.domain.ai.protocols._runtime import ModelClientProtocol
    from app.domain.ai.runtime._context import CallContext
    from app.domain.ai.runtime._model import GeminiModelClient

__all__ = ("AgentRuntime", "BudgetExceededError", "SpanManager", "TurnBudget")


class AgentRuntime:
    """Core re-entrant agent execution loop with TurnBudget and OpenTelemetry SpanManager."""

    __slots__ = ("_budget", "_limits", "_model_client", "_span_manager")

    def __init__(
        self,
        model_client: GeminiModelClient | ModelClientProtocol,
        limits: AgentLimits | TurnBudget | None = None,
        *,
        budget: TurnBudget | None = None,
        span_manager: SpanManager | None = None,
    ) -> None:
        """Initialize the agent runtime with model client, turn budget, and span manager.

        Args:
            model_client: Client managing model communication.
            limits: Execution safety limits or TurnBudget for turns and tool calls.
            budget: Optional explicit TurnBudget instance.
            span_manager: Optional OpenTelemetry SpanManager for turn and tool spans.
        """
        self._model_client = model_client
        resolved_budget, resolved_limits = _normalize_budget(limits=limits, budget=budget)
        self._budget = resolved_budget
        self._limits = resolved_limits
        self._span_manager = span_manager or SpanManager()

    @property
    def budget(self) -> TurnBudget:
        """Configured TurnBudget for this runtime."""
        return self._budget

    @property
    def span_manager(self) -> SpanManager:
        """Configured SpanManager for this runtime."""
        return self._span_manager

    async def execute_turn(
        self,
        *,
        spec_tree: SpecTree,
        session_id: str,
        invocation_id: str,
        user_message: str,
        ctx: CallContext,
        history: list[AgentEvent] | None = None,
        dynamic_context: str | None = None,
    ) -> AsyncIterator[AgentEvent]:
        """Execute one re-entrant conversation turn until completion or budget exhaustion.

        Args:
            spec_tree: Agent hierarchy specification tree.
            session_id: Session identifier.
            invocation_id: Turn invocation identifier.
            user_message: Incoming user prompt message.
            ctx: Active CallContext for tool execution.
            history: Optional conversation history events.
            dynamic_context: Optional dynamic runtime context string.

        Yields:
            AgentEvent instances generated by model streaming or tool execution.
        """
        contents = _build_initial_contents(user_message=user_message, history=history, dynamic_context=dynamic_context)
        turn_span = self._span_manager.start_agent_span(
            agent_name=spec_tree.root.name,
            session_id=session_id,
            turn_id=invocation_id,
            model=spec_tree.root.model,
            provider="google_genai",
        )
        usage_totals = [0, 0]
        turn_error: Exception | None = None
        try:
            async for event in self._iter_turn_events(
                spec_tree=spec_tree,
                session_id=session_id,
                invocation_id=invocation_id,
                ctx=ctx,
                contents=contents,
                usage_totals=usage_totals,
            ):
                yield event
        except Exception as exc:
            turn_error = exc
            raise
        finally:
            self._span_manager.set_usage(turn_span, usage_totals[0], usage_totals[1])
            self._span_manager.end_span(turn_span, error=turn_error)

    async def _iter_turn_events(
        self,
        *,
        spec_tree: SpecTree,
        session_id: str,
        invocation_id: str,
        ctx: CallContext,
        contents: list[Content],
        usage_totals: list[int],
    ) -> AsyncIterator[AgentEvent]:
        current_spec = spec_tree.root
        model_calls = 0
        tool_calls_count = 0

        while model_calls < self._budget.max_turns:
            model_calls += 1
            tools_map: dict[str, Tool] = {t.name: t for t in current_spec.tools}
            tool_decls: list[ToolDeclaration] = [t.declaration() for t in current_spec.tools]
            pending_calls: list[FunctionCall] = []
            accumulated_parts: list[Part] = []
            saw_non_partial = False

            stream_kwargs: dict[str, Any] = {
                "tools": tool_decls,
                "system_instruction": current_spec.static_instruction,
                "model": current_spec.model,
            }
            if current_spec.generation.temperature is not None:
                stream_kwargs["temperature"] = current_spec.generation.temperature
            async for event in self._model_client.generate_stream(contents, **stream_kwargs):
                event = _stamp_event(
                    event=event,
                    session_id=session_id,
                    invocation_id=invocation_id,
                    turn=ctx.turn,
                    agent_name=current_spec.name,
                    usage_totals=usage_totals,
                    accumulated_parts=accumulated_parts,
                    pending_calls=pending_calls,
                )
                if not event.partial:
                    saw_non_partial = True
                yield event

            if pending_calls and (
                tool_calls_count + len(pending_calls) > self._budget.max_tool_calls
                or model_calls >= self._budget.max_turns
            ):
                exceeded_tools = tool_calls_count + len(pending_calls) > self._budget.max_tool_calls
                finish_reason = "TOOL_LIMIT_EXCEEDED" if exceeded_tools else "TURN_LIMIT_EXCEEDED"
                limit_text = (
                    "Tool execution limit reached for this turn."
                    if exceeded_tools
                    else "Model turn limit reached for this turn."
                )
                yield AgentEvent(
                    session_id=session_id,
                    invocation_id=invocation_id,
                    turn=ctx.turn,
                    agent=current_spec.name,
                    finish_reason=finish_reason,
                    partial=False,
                    content=Content(role="model", parts=[Part(text=limit_text)]),
                )
                break

            if not saw_non_partial and accumulated_parts:
                yield AgentEvent(
                    session_id=session_id,
                    invocation_id=invocation_id,
                    turn=ctx.turn,
                    agent=current_spec.name,
                    content=Content(role="model", parts=accumulated_parts),
                    partial=False,
                    actions={"aggregated": True},
                )

            if not pending_calls:
                break

            tool_calls_count += len(pending_calls)

            current_spec, response_parts = await self._dispatch_tools(
                pending_calls=pending_calls,
                model_parts=accumulated_parts,
                current_spec=current_spec,
                spec_tree=spec_tree,
                tools_map=tools_map,
                ctx=ctx,
                contents=contents,
            )

            yield AgentEvent(
                session_id=session_id,
                invocation_id=invocation_id,
                turn=ctx.turn,
                agent=current_spec.name,
                content=Content(role="user", parts=response_parts),
            )

    async def _dispatch_tools(
        self,
        *,
        pending_calls: list[FunctionCall],
        model_parts: list[Part],
        current_spec: AgentSpec,
        spec_tree: SpecTree,
        tools_map: dict[str, Tool],
        ctx: CallContext,
        contents: list[Content],
    ) -> tuple[AgentSpec, list[Part]]:
        """Dispatch parallel tools, update delegation target, and record conversation content."""
        tool_spans = [
            self._span_manager.start_tool_span(tool_name=call.name, call_id=call.id) for call in pending_calls
        ]
        responses = await self._run_tools_with_spans(
            pending_calls=pending_calls, tools_map=tools_map, ctx=ctx, tool_spans=tool_spans
        )

        next_spec = current_spec
        for resp in responses:
            if resp.name == "transfer_to_agent":
                target_name = str(resp.response.get("transferred_to", ""))
                if target_name:
                    next_spec = spec_tree.resolve(target_name)

        response_parts = [Part(function_response=r) for r in responses]
        preserved_model_parts = model_parts or [Part(function_call=c) for c in pending_calls]
        contents.extend([
            Content(role="model", parts=preserved_model_parts),
            Content(role="user", parts=response_parts),
        ])
        return next_spec, response_parts

    async def _run_tools_with_spans(
        self, *, pending_calls: list[FunctionCall], tools_map: dict[str, Tool], ctx: CallContext, tool_spans: list[Any]
    ) -> list[FunctionResponse]:
        try:
            responses = await execute_parallel(pending_calls, tools_map, ctx)
        except Exception as exc:
            for span in tool_spans:
                self._span_manager.end_span(span, error=exc)
            raise
        for span in tool_spans:
            self._span_manager.end_span(span)
        return responses


def _build_initial_contents(
    *, user_message: str, history: list[AgentEvent] | None, dynamic_context: str | None
) -> list[Content]:
    history_events = list(history or [])
    raw_contents: list[Content] = [ev.content for ev in history_events if ev.content]
    start_idx = 0
    while start_idx < len(raw_contents) and not _is_turn_opening_user_content(raw_contents[start_idx]):
        start_idx += 1
    contents = raw_contents[start_idx:]
    user_text = user_message
    if dynamic_context:
        fenced = fence_context_block("ACTIVE_SESSION_CONTEXT", dynamic_context)
        user_text = f"{user_message}\n\n{fenced}"
    contents.append(Content(role="user", parts=[Part(text=user_text)]))
    return contents


def _is_turn_opening_user_content(content: Content) -> bool:
    return content.role == "user" and not any(part.function_response is not None for part in content.parts)


def _stamp_event(
    *,
    event: AgentEvent,
    session_id: str,
    invocation_id: str,
    turn: int,
    agent_name: str,
    usage_totals: list[int],
    accumulated_parts: list[Part],
    pending_calls: list[FunctionCall],
) -> AgentEvent:
    stamped = msgspec.structs.replace(
        event, session_id=session_id, invocation_id=invocation_id, turn=turn, agent=agent_name
    )
    if stamped.usage is not None:
        usage_totals[0] += stamped.usage.prompt_tokens
        usage_totals[1] += stamped.usage.output_tokens
    if stamped.content and stamped.content.parts:
        accumulated_parts.extend(stamped.content.parts)
        pending_calls.extend(p.function_call for p in stamped.content.parts if p.function_call)
    return stamped


def _normalize_budget(
    *, limits: AgentLimits | TurnBudget | None, budget: TurnBudget | None
) -> tuple[TurnBudget, AgentLimits]:
    if budget is not None:
        return budget, AgentLimits(
            max_model_calls_per_turn=budget.max_turns, max_tool_calls_per_turn=budget.max_tool_calls
        )
    if isinstance(limits, TurnBudget):
        return limits, AgentLimits(
            max_model_calls_per_turn=limits.max_turns, max_tool_calls_per_turn=limits.max_tool_calls
        )
    resolved_limits = limits or AgentLimits()
    return (
        TurnBudget(
            max_turns=resolved_limits.max_model_calls_per_turn, max_tool_calls=resolved_limits.max_tool_calls_per_turn
        ),
        resolved_limits,
    )
